#!/usr/bin/env python3
"""Schema of the solver input, generated from the source tree of this checkout.

The schema lists every key and block the solver reads, with its type, default,
and former name. It is extracted from the calls to MIO_InputParameter and
MIO_InputBlock in lanczosKuboCode/Src - the same extraction as
list_input_keys.py - so every version of the code generates its own schema and
nothing is maintained by hand.

    from gendata_schema import generate, lookup   # in memory, always current
    python3 tools/input/gendata_schema.py schema.json   # write a schema to a file

A schema file can be inspected, archived next to an input, or passed to
gendata.py with --schema to convert an input with the schema of another
version of the code.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from typing import Any, Literal, NamedTuple, TypedDict, cast

import click

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from list_input_keys import ROOT, collect, former_names  # noqa: E402

SCHEMA_VERSION = 1

ARRAY = re.compile(r'\[([^\]]*)\]')  # a default of the form [1,2,3]: an array literal


class ArrayInfo(TypedDict):
    """An array-valued key: the kind of its items and how many the solver expects."""

    kind: str
    length: int


class _KeyInfoBase(TypedDict):
    """The fields every key entry has; 'array' is present only for array-valued keys."""

    name: str  # present name, as in the source
    section: str  # part before the first '.', '' when there is none
    defaults: list[str]  # distinct default expressions, as in the source
    readIn: list[str]  # 'file: routine' of the calls that read the key
    type: str  # logical/integer/real/string/array, or mixed/unknown
    formerNames: list[str]  # names before October 2026, which still work


class KeyInfo(_KeyInfoBase, total=False):
    array: ArrayInfo


class BlockInfo(TypedDict, total=False):
    """A block: '&begin Name N'; pattern is present for indexed blocks like 'TB.Hoppings.'."""

    name: str
    readIn: list[str]
    pattern: str  # regex over the normalized name


class SourceStamp(TypedDict):
    """What the schema was generated from, so a stored schema can be traced to a run."""

    version: str
    commit: str | None
    sourceHash: str
    source: str


class Schema(TypedDict):
    """The whole input schema, as generated by generate() and stored by save()."""

    schemaVersion: int
    grabnes: SourceStamp
    keys: dict[str, KeyInfo]  # by normalized name
    blocks: dict[str, BlockInfo]  # by normalized name
    aliases: dict[str, str]  # normalized former name -> normalized present name


EntryInfo = KeyInfo | BlockInfo


class Lookup(NamedTuple):
    """The result of lookup(): kind and name are None when the name is unknown."""

    kind: Literal['key', 'block'] | None
    entry: EntryInfo | None
    name: str | None


def normalize(name: str) -> str:
    """Key form used for matching: lower case, '_' and '-' removed (as in the solver)."""
    return name.lower().replace('_', '').replace('-', '')


def _kind_of_default(default: str) -> str:
    """Type of a key from its default expression: logical/integer/real/string/array/unknown."""
    d = default.strip()
    if d.lower() in ('.true.', '.false.'):
        return 'logical'
    if re.fullmatch(r"'[^']*'|\"[^\"]*\"", d):
        return 'string'
    if re.fullmatch(r'[-+]?\d+', d):
        return 'integer'
    if re.fullmatch(r'[-+]?(\d+\.\d*|\.\d+|\d+)([eEdD][-+]?\d+)?(_dp)?', d):
        return 'real'
    m = ARRAY.fullmatch(d)
    if m and all(re.fullmatch(r'[-+]?[\d.]+', x.strip()) for x in m.group(1).split(',') if x.strip()):
        return 'array'
    return 'unknown'


def _array_info(default: str) -> ArrayInfo | None:
    """Kind and length of an array default like [1,2,3], or None if it is not one."""
    m = ARRAY.fullmatch(default.strip())
    if not m:
        return None
    items = [x.strip() for x in m.group(1).split(',') if x.strip()]
    if not items:
        return None
    kind = 'integer' if all(re.fullmatch(r'[-+]?\d+', x) for x in items) else 'real'
    return {'kind': kind, 'length': len(items)}


def _grabnes_version() -> str:
    """Version from pyproject.toml, without importing toml parsers that are not needed here."""
    path = os.path.join(ROOT, 'pyproject.toml')
    try:
        with open(path) as f:
            for line in f:
                m = re.match(r'\s*version\s*=\s*"([^"]+)"', line)
                if m:
                    return m.group(1)
    except OSError:
        pass
    return 'unknown'


def _source_hash(src: str) -> str:
    """A short hash of the Fortran sources, so a schema can be tied to the exact code."""
    h = hashlib.sha256()
    for folder, dirs, files in os.walk(src):
        dirs.sort()
        for name in sorted(files):
            if name.lower().endswith(('.f90', '.F90', '.inc')):
                p = os.path.join(folder, name)
                h.update(os.path.relpath(p, src).encode())
                with open(p, 'rb') as f:
                    h.update(f.read())
    return h.hexdigest()[:16]


def _git_describe() -> str | None:
    """`git describe` of the checkout, or None outside a git repository."""
    try:
        return (
            subprocess.run(
                ['git', '-C', ROOT, 'describe', '--always', '--dirty'],
                capture_output=True,
                text=True,
                timeout=5,
            ).stdout.strip()
            or None
        )
    except (OSError, subprocess.SubprocessError):
        return None


def generate(src: str | None = None) -> Schema:
    """The schema of the source tree `src` (default: lanczosKuboCode/Src of this checkout)."""
    src = src or os.path.join(ROOT, 'lanczosKuboCode', 'Src')
    rows: dict[tuple[str, str], list[Any]]
    rawblocks: dict[str, list[Any]]
    rows, rawblocks = collect()
    former: dict[str, list[str]] = former_names()

    keys: dict[str, dict[str, Any]] = {}
    for (_k, _default), (key, dflt, _kind, where) in rows.items():
        n = normalize(key)
        typ = _kind_of_default(dflt)
        entry = keys.setdefault(
            n,
            {
                'name': key,
                'section': key.split('.')[0] if '.' in key else '',
                'types': set(),
                'defaults': [],
                'readIn': [],
            },
        )
        entry['types'].add(typ)
        entry['defaults'].append(dflt)
        entry['readIn'] += where
        if ARRAY.fullmatch(dflt.strip()) and 'array' not in entry:
            info = _array_info(dflt)
            if info:
                entry['array'] = info
    for n, entry in keys.items():
        types: set[str] = entry.pop('types')
        entry['defaults'] = sorted(set(entry['defaults']))
        entry['readIn'] = sorted(set(entry['readIn']))
        entry['type'] = types.pop() if len(types) == 1 else 'mixed' if 'unknown' not in types else 'unknown'
        # table order, not sorted: the solver tries the former names in this order
        entry['formerNames'] = list(former.get(n, []))

    blocks: dict[str, BlockInfo] = {}
    for n, (name, where) in rawblocks.items():
        blk: BlockInfo = {'name': name, 'readIn': sorted(set(where))}
        if name.endswith('.'):
            blk['pattern'] = normalize(name) + r'\d+'  # TB.Hoppings. matches TB.Hoppings.2
        blocks[n] = blk

    aliases: dict[str, str] = {}
    for new, olds in former.items():
        for old in olds:
            aliases[normalize(old)] = new

    schema: Schema = {
        'schemaVersion': SCHEMA_VERSION,
        'grabnes': {
            'version': _grabnes_version(),
            'commit': _git_describe(),
            'sourceHash': _source_hash(src),
            'source': os.path.relpath(src, ROOT),
        },
        'keys': cast('dict[str, KeyInfo]', keys),
        'blocks': blocks,
        'aliases': aliases,
    }
    return schema


def lookup(schema: Schema, name: str) -> Lookup:
    """(kind, entry, canonical) for a key or block name as written; kind is 'key', 'block' or None.

    Matching ignores case, '_' and '-', and resolves former names. `canonical` is the present
    name of the key, which differs from `name` when an alias was used.
    """
    n = normalize(name)
    entry = schema['keys'].get(n)
    if entry:
        return Lookup('key', entry, entry['name'])
    block = schema['blocks'].get(n)
    if block:
        return Lookup('block', block, block['name'])
    for blk in schema['blocks'].values():
        if 'pattern' in blk and re.fullmatch(blk['pattern'], n):
            return Lookup('block', blk, name)
    aliased = schema['aliases'].get(n)
    if aliased:
        entry = schema['keys'][aliased]
        return Lookup('key', entry, entry['name'])
    return Lookup(None, None, None)


def load(path: str) -> Schema:
    """A schema stored by save(); a file of another schema version is refused."""
    with open(path) as f:
        schema: Schema = json.load(f)
    if schema.get('schemaVersion') != SCHEMA_VERSION:
        raise ValueError(
            f'{path}: schema version {schema.get("schemaVersion")}, this tool reads {SCHEMA_VERSION}'
        )
    return schema


def save(schema: Schema, path: str) -> None:
    """Store a schema as JSON, sorted so that two runs of the same source diff cleanly."""
    with open(path, 'w') as f:
        json.dump(schema, f, indent=1, sort_keys=True)
        f.write('\n')


@click.command()
@click.argument('output', type=click.Path(), required=False)
def main(output: str | None) -> None:
    """Write the input schema of this source tree (default: stdout)."""
    schema = generate()
    if output:
        save(schema, output)
        click.echo(
            f'wrote {output}: {len(schema["keys"])} keys, {len(schema["blocks"])} blocks, '
            f'grabnes {schema["grabnes"]["version"]} ({schema["grabnes"]["commit"]})'
        )
    else:
        click.echo(json.dumps(schema, indent=1, sort_keys=True))


if __name__ == '__main__':
    main()
